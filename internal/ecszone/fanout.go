package ecszone

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"
)

type ZoneTraffic struct {
	Zone       string
	Subnet     string
	Queries    int
	SubnetHits int
}

func AddTraffic(byZone map[string]*ZoneTraffic, zone, subnet string, n int) {
	province, carrier := SplitZone(zone)
	if province == "" || carrier == "" {
		return
	}
	prefix, err := netip.ParsePrefix(subnet)
	if err != nil || !prefix.Addr().Is4() || prefix.Bits() != 24 {
		return
	}
	t := byZone[zone]
	if t == nil {
		t = &ZoneTraffic{Zone: zone}
		byZone[zone] = t
	}
	t.Queries += n
	if n > t.SubnetHits || (n == t.SubnetHits && prefix.Masked().String() < t.Subnet) {
		t.Subnet, t.SubnetHits = prefix.Masked().String(), n
	}
}

func PickFanout(byZone map[string]*ZoneTraffic, minQueries, maxZones int) []ZoneTraffic {
	var out []ZoneTraffic
	for _, t := range byZone {
		if t.Queries >= minQueries && t.Subnet != "" {
			out = append(out, *t)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Queries != out[j].Queries {
			return out[i].Queries > out[j].Queries
		}
		return out[i].Zone < out[j].Zone
	})
	if len(out) > maxZones {
		out = out[:maxZones]
	}
	if len(out) < 2 {
		return nil
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Zone < out[j].Zone })
	return out
}

func RenderFanout(picked []ZoneTraffic, days int) string {
	var b strings.Builder
	b.WriteString("# generated by dns-stack routing-data (ecs-fanout)\n")
	fmt.Fprintf(&b, "# 最近 %d 天客户端实际用到的分片；其中一个分片拿到按子网调度的答案时，mosproxy 替其余分片各问一次\n", days)
	for _, t := range picked {
		fmt.Fprintf(&b, "%s,%s\n", t.Zone, t.Subnet)
	}
	return b.String()
}
